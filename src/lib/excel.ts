import type { ExportDataset, ImportRow } from "./types"

// ExcelJS runs fully in the browser. It is loaded lazily so it doesn't weigh down first paint.
async function loadExcel() {
  const mod = await import("exceljs")
  return mod.default
}

function download(buffer: ArrayBuffer, filename: string) {
  const blob = new Blob([buffer], { type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet" })
  const url = URL.createObjectURL(blob)
  const a = document.createElement("a")
  a.href = url
  a.download = filename
  document.body.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 2000)
}

function argb(hex: string) {
  return "FF" + hex.replace("#", "").toUpperCase()
}

export async function exportWorkbook(datasets: ExportDataset[], opts: { filename: string; siteName: string; author: string; color: string }) {
  const ExcelJS = await loadExcel()
  const wb = new ExcelJS.Workbook()
  wb.creator = `OpsHub — ${opts.author}`
  wb.created = new Date()
  for (const ds of datasets) {
    const ws = wb.addWorksheet(ds.label.slice(0, 31), { views: [{ state: "frozen", ySplit: 1 }] })
    ws.columns = ds.columns.map((c) => ({ header: c.header, key: c.key, width: c.width ?? 16, style: c.numFmt ? { numFmt: c.numFmt } : undefined }))
    for (const row of ds.rows) {
      const out: Record<string, unknown> = {}
      for (const c of ds.columns) out[c.key] = row[c.key] ?? ""
      ws.addRow(out)
    }
    const header = ws.getRow(1)
    header.font = { bold: true, color: { argb: "FFFFFFFF" } }
    header.fill = { type: "pattern", pattern: "solid", fgColor: { argb: argb(opts.color) } }
    header.alignment = { vertical: "middle" }
    header.height = 20
    ws.autoFilter = { from: { row: 1, column: 1 }, to: { row: 1, column: ds.columns.length } }
  }
  const info = wb.addWorksheet("About")
  info.addRows([
    ["Generated by", "OpsHub (frontend prototype)"],
    ["Unit", opts.siteName],
    ["Exported by", opts.author],
    ["Exported at", new Date().toLocaleString("en-IN")],
    ["Company", "MahaPower Utility"],
  ])
  info.getColumn(1).width = 16
  info.getColumn(2).width = 44
  info.getColumn(1).font = { bold: true }
  const buf = await wb.xlsx.writeBuffer()
  download(buf as ArrayBuffer, opts.filename)
}

const HEADER_MAP: [keyof ImportRow, RegExp][] = [
  ["name", /^(item|item name|name|description)$/i],
  ["category", /^category$/i],
  ["unit", /^(unit|uom)$/i],
  ["qty", /^(qty|quantity|stock|qty on hand)$/i],
  ["unitPrice", /^(unit price|price|rate)( ?\(₹\))?$/i],
  ["reorderLevel", /^(reorder|reorder level|min stock)$/i],
]

function cellValue(v: unknown): unknown {
  if (v && typeof v === "object") {
    const o = v as { result?: unknown; text?: string; richText?: { text: string }[] }
    if ("result" in o) return o.result
    if (o.richText) return o.richText.map((r) => r.text).join("")
    if (o.text !== undefined) return o.text
    if (v instanceof Date) return v.toISOString()
  }
  return v
}

export interface ParsedImport {
  rows: ImportRow[]
  missingColumns: string[]
  sheetName: string
}

export async function parseInventoryFile(file: File): Promise<ParsedImport> {
  const ExcelJS = await loadExcel()
  const wb = new ExcelJS.Workbook()
  await wb.xlsx.load(await file.arrayBuffer())
  const ws = wb.worksheets.find((w) => w.rowCount > 1) ?? wb.worksheets[0]
  if (!ws) throw new Error("The workbook has no sheets")
  const colFor: Partial<Record<keyof ImportRow, number>> = {}
  ws.getRow(1).eachCell((cell, col) => {
    const text = String(cellValue(cell.value) ?? "").trim()
    for (const [key, re] of HEADER_MAP) if (re.test(text) && colFor[key] === undefined) colFor[key] = col
  })
  const missingColumns = HEADER_MAP.filter(([k]) => colFor[k] === undefined).map(([k]) => k)
  const rows: ImportRow[] = []
  ws.eachRow((row, idx) => {
    if (idx === 1) return
    const get = (k: keyof ImportRow) => (colFor[k] ? cellValue(row.getCell(colFor[k]!).value) : undefined)
    const name = String(get("name") ?? "").trim()
    if (!name) return
    const num = (k: keyof ImportRow) => {
      const v = get(k)
      return v === undefined || v === null || v === "" ? (NaN as number) : Number(v)
    }
    rows.push({
      name,
      category: String(get("category") ?? "").trim(),
      unit: String(get("unit") ?? "Nos").trim() || "Nos",
      qty: num("qty"),
      unitPrice: num("unitPrice"),
      reorderLevel: Number.isNaN(num("reorderLevel")) ? 0 : num("reorderLevel"),
    })
  })
  return { rows, missingColumns, sheetName: ws.name }
}

export async function downloadTemplate(categories: string[]) {
  await exportWorkbook(
    [
      {
        id: "template",
        label: "Inventory",
        columns: [
          { key: "name", header: "Item", width: 36 },
          { key: "category", header: "Category", width: 18 },
          { key: "unit", header: "Unit", width: 10 },
          { key: "qty", header: "Qty", width: 10 },
          { key: "unitPrice", header: "Unit Price", width: 12 },
          { key: "reorderLevel", header: "Reorder Level", width: 14 },
        ],
        rows: [
          { name: "Single Phase Smart Meter", category: categories[0] ?? "Meters", unit: "Nos", qty: 520, unitPrice: 2400, reorderLevel: 100 },
          { name: "Cable Tie 300 mm (pack of 100)", category: categories[categories.length - 1] ?? "Spares", unit: "Sets", qty: 60, unitPrice: 180, reorderLevel: 20 },
        ],
      },
    ],
    { filename: "opshub-inventory-template.xlsx", siteName: "Template", author: "OpsHub", color: "#334155" },
  )
}
